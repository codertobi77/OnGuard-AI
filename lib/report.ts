// ---------------------------------------------------------------------------
// Text helpers
// ---------------------------------------------------------------------------

function wrapText(
  text: string,
  font: PDFFont,
  size: number,
  maxWidth: number,
): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word;
    if (font.widthOfTextAtSize(candidate, size) <= maxWidth) {
      current = candidate;
    } else {
      if (current) lines.push(current);
      current = word;
    }
  }
  if (current) lines.push(current);
  return lines.length > 0 ? lines : [""];
}

function formatDate(date: Date, lang: Lang): string {
  return new Intl.DateTimeFormat(lang === "fr" ? "fr-FR" : "en-GB", {
    dateStyle: "long",
    timeStyle: "short",
    timeZone: "UTC",
  }).format(date);
}

// ---------------------------------------------------------------------------
// Report builder
// ---------------------------------------------------------------------------

export interface ReportPdfParams {
  result: AnalysisResult;
  clinicalData: ClinicalData;
  createdAt: Date;
  lang: Lang;
  assessmentId?: string;
  modelId?: string;
  demoMode?: boolean;
  /** True when ABCDE details are unavailable (archived database record). */
  abcdeNotStored?: boolean;
}

const PAGE_WIDTH = 595.28;
const PAGE_HEIGHT = 841.89;
const MARGIN = 44;
const CONTENT_WIDTH = PAGE_WIDTH - 2 * MARGIN;

export async function buildReportPdf(
  params: ReportPdfParams,
): Promise<Uint8Array> {
  const { result, clinicalData, createdAt, lang, assessmentId, modelId } =
    params;

  const text = REPORT_TEXT[lang];
  const accent = riskColor(result.riskScore);

  const pdf = await PDFDocument.create();
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);

  if (assessmentId) {
    pdf.setTitle(`OnGuard AI - ${assessmentId}`);
  }
  pdf.setProducer("OnGuard AI");
  pdf.setCreator("OnGuard AI - LiteTECH Startup");

  let page: PDFPage = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]);

  // ----------------------------------------------------------------- header
  page.drawRectangle({
    x: 0,
    y: PAGE_HEIGHT - 64,
    width: PAGE_WIDTH,
    height: 64,
    color: C.teal,
  });
  page.drawText("OnGuard AI", {
    x: MARGIN,
    y: PAGE_HEIGHT - 36,
    size: 22,
    font: bold,
    color: C.white,
  });
  page.drawText(text.reportTitle, {
    x: MARGIN,
    y: PAGE_HEIGHT - 52,
    size: 11,
    font: regular,
    color: C.white,
  });
  const dateStr = formatDate(createdAt, lang);
  const dateWidth = bold.widthOfTextAtSize(dateStr, 9);
  page.drawText(dateStr, {
    x: PAGE_WIDTH - MARGIN - dateWidth,
    y: PAGE_HEIGHT - 36,
    size: 9,
    font: bold,
    color: C.white,
  });

  let y = PAGE_HEIGHT - 88;

  const ensureSpace = (needed: number) => {
    if (y - needed < 96) {
      page = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
      y = PAGE_HEIGHT - MARGIN;
      drawFooter(page);
    }
  };

  const drawFooter = (target: PDFPage) => {
    target.drawLine({
      start: { x: MARGIN, y: 66 },
      end: { x: PAGE_WIDTH - MARGIN, y: 66 },
      thickness: 0.75,
      color: C.lightGray,
    });
    const disclaimerLines = wrapText(text.disclaimer, regular, 7.5, CONTENT_WIDTH);
    let fy = 54;
    for (const line of disclaimerLines) {
      target.drawText(line, { x: MARGIN, y: fy, size: 7.5, font: regular, color: C.slate });
      fy -= 10;
    }
    target.drawText(text.footer, {
      x: MARGIN,
      y: fy - 2,
      size: 7.5,
      font: regular,
      color: C.slate,
    });
  };

  // ------------------------------------------------------------ meta line
  const metaParts: string[] = [];
  if (assessmentId) metaParts.push(`${text.reference}: ${assessmentId}`);
  metaParts.push(
    `${text.engine}: ${params.demoMode ? text.demoEngine : modelId ?? "OpenRouter"}`,
  );
  page.drawText(metaParts.join("  |  "), {
    x: MARGIN,
    y,
    size: 8.5,
    font: regular,
    color: C.slate,
  });
  y -= 30;

  // ------------------------------------------------------------- risk score
  const scoreLabel = text.score;
  page.drawText(scoreLabel.toUpperCase(), {
    x: MARGIN,
    y: y - 2,
    size: 9,
    font: bold,
    color: C.slate,
  });
  y -= 24;

  const scoreText = result.riskScore.toFixed(1);
  page.drawText(scoreText, {
    x: MARGIN,
    y: y - 40,
    size: 44,
    font: bold,
    color: accent,
  });
  const scoreWidth = bold.widthOfTextAtSize(scoreText, 44);
  page.drawText("/ 10", {
    x: MARGIN + scoreWidth + 6,
    y: y - 40,
    size: 14,
    font: regular,
    color: C.slate,
  });
  const levelStr = riskLevelLabels[lang][result.riskLevel];
  page.drawText(levelStr, {
    x: MARGIN + scoreWidth + 12,
    y: y - 22,
    size: 13,
    font: bold,
    color: accent,
  });
  page.drawText(text.level, {
    x: MARGIN + scoreWidth + 12,
    y: y - 38,
    size: 8.5,
    font: regular,
    color: C.slate,
  });
  y -= 58;

  // Gauge: green (0-40%), orange (40-70%), red (70-100%) with score marker.
  const gaugeY = y;
  const gaugeH = 10;
  page.drawRectangle({ x: MARGIN, y: gaugeY, width: CONTENT_WIDTH * 0.4, height: gaugeH, color: C.green });
  page.drawRectangle({ x: MARGIN + CONTENT_WIDTH * 0.4, y: gaugeY, width: CONTENT_WIDTH * 0.3, height: gaugeH, color: C.orange });
  page.drawRectangle({ x: MARGIN + CONTENT_WIDTH * 0.7, y: gaugeY, width: CONTENT_WIDTH * 0.3, height: gaugeH, color: C.red });
  const markerX = MARGIN + (Math.min(Math.max(result.riskScore, 0), 10) / 10) * CONTENT_WIDTH;
  page.drawRectangle({ x: markerX - 1.5, y: gaugeY - 4, width: 3, height: gaugeH + 8, color: C.nightBlue });
  y = gaugeY - 24;

  // ------------------------------------------------------------ ABCDE grid
  const sectionTitle = (title: string) => {
    ensureSpace(34);
    page.drawText(title, {
      x: MARGIN,
      y,
      size: 10.5,
      font: bold,
      color: C.teal,
    });
    y -= 6;
    page.drawLine({
      start: { x: MARGIN, y },
      end: { x: PAGE_WIDTH - MARGIN, y },
      thickness: 0.75,
      color: C.lightGray,
    });
    y -= 16;
  };

  const keyValues: Array<[string, string]> = [
    [text.asymmetry, result.abcdeAssessment.asymmetry],
    [text.border, result.abcdeAssessment.border],
    [text.color, result.abcdeAssessment.color],
    [text.diameter, result.abcdeAssessment.diameter],
  ];

  sectionTitle(text.abcde);
  if (params.abcdeNotStored) {
    const lines = wrapText(text.abcdeNotStored, regular, 10, CONTENT_WIDTH);
    ensureSpace(lines.length * 14 + 8);
    for (const line of lines) {
      page.drawText(line, { x: MARGIN, y, size: 10, font: regular, color: C.slate });
      y -= 14;
    }
    y -= 6;
  } else {
    const labelX = MARGIN;
    const valueX = MARGIN + 92;
    const valueWidth = CONTENT_WIDTH - 92;
    for (const [label, value] of keyValues) {
      const lines = wrapText(value, regular, 10, valueWidth);
      ensureSpace(lines.length * 14 + 4);
      page.drawText(label, { x: labelX, y, size: 10, font: bold, color: C.nightBlue });
      let vy = y;
      for (const line of lines) {
        page.drawText(line, { x: valueX, y: vy, size: 10, font: regular, color: C.slate });
        vy -= 14;
      }
      y = Math.min(vy, y - 14) - 2;
    }
    y -= 6;
  }

  // ------------------------------------------------------ clinical profile
  sectionTitle(text.clinical);
  const colWidth = CONTENT_WIDTH / 2;
  const symptomsStr =
    clinicalData.symptoms.length > 0
      ? clinicalData.symptoms.map((s) => symptomLabels[lang][s]).join(", ")
      : text.none;
  const profile: Array<[string, string]> = [
    [text.location, locationLabels[lang][clinicalData.lesionLocation]],
    [text.duration, durationLabels[lang][clinicalData.duration]],
    [text.symptoms, symptomsStr],
    [text.family, clinicalData.familyHistory ? text.yes : text.no],
  ];
  const profileRows: Array<Array<[string, string]>> = [
    [profile[0], profile[1]],
    [profile[2], profile[3]],
  ];
  for (const row of profileRows) {
    const lineCounts = row.map(
      ([, value]) => wrapText(value, regular, 10, colWidth - 96).length,
    );
    ensureSpace(Math.max(...lineCounts) * 14 + 4);
    for (const [index, [label, value]] of row.entries()) {
      const colX = MARGIN + index * colWidth;
      page.drawText(label, { x: colX, y, size: 10, font: bold, color: C.nightBlue });
      let vy = y - 14;
      for (const line of wrapText(value, regular, 10, colWidth - 96)) {
        page.drawText(line, { x: colX, y: vy, size: 10, font: regular, color: C.slate });
        vy -= 14;
      }
    }
    y -= Math.max(...lineCounts) * 14 + 8;
  }

  // ------------------------------------------------------------- rationale
  sectionTitle(text.rationale);
  const rationaleLines = wrapText(result.clinicalRationale, regular, 10, CONTENT_WIDTH);
  ensureSpace(rationaleLines.length * 14 + 8);
  for (const line of rationaleLines) {
    page.drawText(line, { x: MARGIN, y, size: 10, font: regular, color: C.slate });
    y -= 14;
  }
  y -= 10;

  // --------------------------------------------------------- recommendation
  ensureSpace(60);
  page.drawText(text.recommendation, {
    x: MARGIN,
    y,
    size: 10.5,
    font: bold,
    color: C.teal,
  });
  y -= 8;
  page.drawLine({
    start: { x: MARGIN, y },
    end: { x: PAGE_WIDTH - MARGIN, y },
    thickness: 0.75,
    color: C.lightGray,
  });
  y -= 16;

  const recLines = wrapText(result.recommendation, regular, 10.5, CONTENT_WIDTH - 24);
  ensureSpace(recLines.length * 15 + 20);
  const boxTop = y + 6;
  page.drawRectangle({
    x: MARGIN,
    y: boxTop - recLines.length * 15 - 12,
    width: CONTENT_WIDTH,
    height: recLines.length * 15 + 18,
    color: accent,
    opacity: 0.08,
  });
  page.drawRectangle({
    x: MARGIN,
    y: boxTop - recLines.length * 15 - 12,
    width: 4,
    height: recLines.length * 15 + 18,
    color: accent,
  });
  let ry = y;
  for (const line of recLines) {
    page.drawText(line, { x: MARGIN + 16, y: ry, size: 10.5, font: regular, color: C.nightBlue });
    ry -= 15;
  }
  y = ry - 12;

  drawFooter(page);
  return pdf.save();
}
